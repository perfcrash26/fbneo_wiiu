#!/usr/bin/env python3
# Generate src/cpu/sh4/sh4_optable.inc from the existing execute_one* switch bodies in sh4.cpp.
# Transform: every leaf  "NAME(opcode); break;"  ->  "return (sh3op)&NAME;"
# and the group calls to execute_one_0000/4000 -> "return sh3_decode_0000/4000(opcode);".
# This makes the optable a pure, mechanical mirror of the interpreter's dispatch (single source of
# truth), so it cannot disagree except via a bug caught by the bench frame hashes.
# Usage (from the repo root): python3 tools/gen_sh3_optable.py
import re, sys

SH4 = 'src/cpu/sh4/sh4.cpp'
OUT = 'src/cpu/sh4/sh4_optable.inc'
lines = open(SH4).read().split('\n')

def extract(sig):
    for i,l in enumerate(lines):
        if re.search(sig, l):
            depth=0; started=False; body=[]
            for j in range(i, len(lines)):
                body.append(lines[j])
                depth += lines[j].count('{') - lines[j].count('}')
                if '{' in lines[j]: started=True
                if started and depth==0:
                    return body
    sys.exit('not found: '+sig)

targets = [
    ('execute_one_0000', r'static inline void execute_one_0000\('),
    ('execute_one_4000', r'static inline void execute_one_4000\('),
    ('execute_one',      r'static inline void execute_one\(const UINT16'),
]

def xform(body):
    out=[]
    for l in body:
        # rename tokens (longest first)
        l = l.replace('execute_one_0000','sh3_decode_0000').replace('execute_one_4000','sh3_decode_4000')
        l = re.sub(r'\bexecute_one\b','sh3_decode', l)
        # signature: static inline void sh3_decode* -> static sh3op sh3_decode*
        l = re.sub(r'static inline void (sh3_decode\w*)', r'static sh3op \1', l)
        # sub-decoder group dispatch: [case ...:] sh3_decode_0000(opcode); [break;] -> return sh3_decode_0000(opcode);
        m = re.match(r'^(\s*)(case 0x[0-9a-f]+:\s*)?(sh3_decode_(?:0000|4000))\(opcode\);(\s*break;)?\s*$', l)
        if m:
            out.append(f'{m.group(1)}{m.group(2) or ""}return {m.group(3)}(opcode);')
            out.append(('CONV',)); continue
        # leaf handler: [case ...:] NAME(opcode); [break;] -> return (sh3op)&NAME;
        m = re.match(r'^(\s*)(case 0x[0-9a-f]+:\s*)?([A-Za-z_]\w*)\(opcode\);(\s*break;)?\s*$', l)
        if m:
            out.append(f'{m.group(1)}{m.group(2) or ""}return (sh3op)&{m.group(3)};')
            out.append(('CONV',)); continue
        # drop a lone "break;" immediately after a converted return (from multi-line single-handler groups)
        if out and out[-1]==('CONV',) and l.strip()=='break;':
            out[-1]=None; continue   # remove the CONV marker; skip this break
        if out and out[-1]==('CONV',):
            out[-1]=None             # clear marker, keep normal flow
        out.append(l)
    # drop markers, insert a fallthrough return before each function's final closing brace
    res=[x for x in out if x not in (None,('CONV',))]
    # insert "return (sh3op)&op_nul;" before the last line (closing } of the function)
    for k in range(len(res)-1,-1,-1):
        if res[k].strip()=='}':
            res.insert(k, '\treturn (sh3op)&op_nul;')
            break
    return res

hdr = [
'// GENERATED by tools/gen_sh3_optable.py from sh4.cpp execute_one* - do not edit by hand.',
'// Regenerate from the repo root: python3 tools/gen_sh3_optable.py',
'typedef void (*sh3op)(const UINT16);',
'static void op_nul(const UINT16) { }   // unmatched opcode: interpreter switch fell through (no-op)',
'',
]
blocks=[]
for name,sig in targets:
    blocks.append('\n'.join(xform(extract(sig))))
tail = [
'',
'static sh3op sh3_optable[0x10000];',
'static int sh3_optable_built = 0;',
'static void sh3_build_optable(void)',
'{',
'\tfor (UINT32 i = 0; i < 0x10000; i++) sh3_optable[i] = sh3_decode((UINT16)i);',
'\tsh3_optable_built = 1;',
'}',
]
open(OUT,'w').write('\n'.join(hdr) + '\n'.join(blocks) + '\n' + '\n'.join(tail) + '\n')
print('wrote', OUT)
# quick stats
txt=open(OUT).read()
print('return (sh3op)& leaves:', txt.count('return (sh3op)&'))
print('sub-decoder returns   :', txt.count('return sh3_decode_000'))
print('functions             :', txt.count('static sh3op sh3_decode'))
